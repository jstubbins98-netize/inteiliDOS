#define DAISY_NOTE_COUNT ((int)(sizeof(daisy_melody)/sizeof(daisy_melody[0])))

/* =========================================================================
 * Combined playback: music + ASCII art drawn character-by-character
 *
 * Art chars are spread evenly across all notes so the final character
 * of the console art lands exactly at the last note.
 * ========================================================================= */
static void play_with_art(void) {
    int ac = 0;   /* next art char index */

    for (int i = 0; i < DAISY_NOTE_COUNT; i++) {

        /* Output every art char whose scheduled note index <= i */
        while (ac < art_total &&
               (ac * DAISY_NOTE_COUNT / art_total) <= i) {
            vga_set_cursor(art_buf[ac].row, art_buf[ac].col);
            vga_putchar(art_buf[ac].ch);
            ac++;
        }

        int ms = daisy_melody[i].ms;
        if (ms < 1) ms = 1;
        if (daisy_melody[i].freq == 0)
            speaker_off();
        else
            speaker_on(daisy_melody[i].freq);
        timer_sleep((uint32_t)ms);
    }

    speaker_off();

    /* flush any remaining chars (rounding artefacts) */
    while (ac < art_total) {
        vga_set_cursor(art_buf[ac].row, art_buf[ac].col);
        vga_putchar(art_buf[ac].ch);
        ac++;
    }
}

/* =========================================================================
 * Public entry point
 * ========================================================================= */
void daisy_play(void) {
    /* Clear to cyan-on-black */
    vga_set_color(VGA_COLOR_LIGHT_CYAN, VGA_COLOR_BLACK);
    vga_clear();

    /* Build the flat char buffer */
    build_art_chars();

    /* Play music while drawing the console art */
    play_with_art();

    /* Restore normal colour */
    vga_set_color(VGA_COLOR_WHITE, VGA_COLOR_BLACK);
}

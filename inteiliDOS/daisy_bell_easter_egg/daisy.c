/* =========================================================================
 * Flat (row, col, char) buffer built at runtime from the art array
 * ========================================================================= */
typedef struct { uint8_t row; uint8_t col; char ch; } ArtChar;
static ArtChar art_buf[2048];
static int     art_total = 0;

static void build_art_chars(void) {
    art_total = 0;
    for (int r = 0; r < ART_ROWS && art_total < 2048; r++) {
        const char *s = ibm7094_art[r];
        int col = ART_COL;
        int vga_row = r + 1;  /* VGA rows 1-22, leaving row 0 and 23-24 clear */
        for (; *s && art_total < 2048; s++, col++) {
            art_buf[art_total].row = (uint8_t)vga_row;
            art_buf[art_total].col = (uint8_t)col;
            art_buf[art_total].ch  = *s;
            art_total++;
        }
    }
}


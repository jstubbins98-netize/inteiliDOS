/*
 * inteiliDOS -- daisy_bell_easter_egg/daisy.c
 * Easter egg: draws an IBM 7094 operator's console ASCII art on screen
 * while playing "Daisy Bell" through the PC speaker.
 *
 * Trigger: type  DAISY  at the IntelliShell prompt.
 *
 * Historical note: on 17 April 1961 an IBM 7094 at Bell Labs, Murray Hill NJ,
 * became the first computer to sing.  It sang this song.
 * The performance was arranged by John L. Kelly and Carol Lockbaum.
 *
 * Visual: cyan text on black, full 80x25 VGA screen.
 * Art characters are written one-by-one, spread evenly across the 653 notes,
 * so the last character of the art lands on the final note (~214 s).
 */


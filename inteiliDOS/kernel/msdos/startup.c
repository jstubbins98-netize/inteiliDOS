/* Add the sound environment to a saved private DOS volume, preserving the
 * user's startup commands. New file data uses a fresh chain; the directory
 * switches only after that data and both FAT copies have been written. */
#include "startup.h"
#include "../memory.h"

static unsigned get16(const uint8_t *p) {return p[0]|((unsigned)p[1]<<8);}
static uint32_t get32(const uint8_t *p) {return get16(p)|((uint32_t)get16(p+2)<<16);}
static void set16(uint8_t *p,unsigned n) {p[0]=n;p[1]=n>>8;}
static void set32(uint8_t *p,uint32_t n) {set16(p,n);set16(p+2,n>>16);}

static int has_blaster(const uint8_t *text,unsigned size) {
    const char wanted[]=MSDOS_BLASTER_LINE;
    for (unsigned at=0;at<size;) {
        unsigned end=at;
        while (end<size && text[end]!='\r' && text[end]!='\n') ++end;
        unsigned first=at,last=end;
        while (first<last && (text[first]==' ' || text[first]=='\t')) ++first;
        while (last>first && (text[last-1]==' ' || text[last-1]=='\t')) --last;
        if (last-first==sizeof(wanted)-1) {
            unsigned i=0;
            for (;i<sizeof(wanted)-1;i++) {
                unsigned c=text[first+i];
                if (c>='a' && c<='z') c-=32;
                if (c!=(unsigned)wanted[i]) break;
            }
            if (i==sizeof(wanted)-1) return 1;
        }
        at=end;
        while (at<size && (text[at]=='\r' || text[at]=='\n')) ++at;
    }
    return 0;
}

int msdos_startup_sound(fs_image_t *disk) {
    uint8_t sector[512];
    /* Exact layout generated by seed_disk(), not an arbitrary FAT editor. */
    if (disk->sectors!=520u*63u ||
        fs_image_sector(disk,1,sector,0) ||
        get16(sector+11)!=512 || sector[13]!=4 ||
        get16(sector+14)!=1 || sector[16]!=2 ||
        get16(sector+17)!=512 || get16(sector+22)!=32 ||
        get32(sector+28)!=1 || get16(sector+19)!=disk->sectors-1 ||
        sector[510]!=0x55 || sector[511]!=0xaa) return -1;
    uint8_t *fat=kmalloc(16384),*root=kmalloc(16384),*text=kmalloc(65536);
    int rc=-1;
    if (!fat || !root || !text) goto done;
    for (unsigned i=0;i<32;i++)
        if (fs_image_sector(disk,2+i,fat+i*512,0) ||
            fs_image_sector(disk,66+i,root+i*512,0)) goto done;
    int entry=-1,free_entry=-1;
    for (unsigned i=0;i<512;i++) {
        uint8_t *e=root+i*32;
        if ((!e[0] || e[0]==0xe5) && free_entry<0) free_entry=i;
        if (!e[0]) break;
        if (e[0]!=0xe5 && !(e[11]&0x18) &&
            !kmemcmp(e,"AUTOEXECBAT",11)) {entry=i;break;}
    }
    if (entry<0) entry=free_entry;
    if (entry<0) goto done;
    uint8_t *e=root+entry*32;
    int exists=e[0] && e[0]!=0xe5;
    unsigned size=exists?get32(e+28):0;
    if (size>65536-64) goto done;
    unsigned old[32],old_count=0,cluster=exists?get16(e+26):0;
    for (unsigned offset=0;offset<size;offset+=2048) {
        if (cluster<2 || cluster>=8167 || old_count>=32) goto done;
        for (unsigned i=0;i<old_count;i++) if (old[i]==cluster) goto done;
        old[old_count++]=cluster;
        for (unsigned i=0;i<4;i++)
            if (fs_image_sector(disk,98+(cluster-2)*4+i,text+offset+i*512,0)) goto done;
        cluster=get16(fat+cluster*2);
    }
    if ((size && cluster<0xfff8) || (!size && cluster)) goto done;
    /* DOS treats Ctrl-Z as end-of-file. Append before it, not after it. */
    for (unsigned i=0;i<size;i++) if (text[i]==0x1a) {size=i;break;}
    if (has_blaster(text,size)) {rc=0;goto done;}
    if (exists && (e[11]&1)) goto done; /* respect read-only startup files */
    if (size && text[size-1]!='\n') {text[size++]='\r';text[size++]='\n';}
    const char line[]=MSDOS_BLASTER_LINE "\r\n";
    kmemcpy(text+size,line,sizeof(line)-1);size+=sizeof(line)-1;
    unsigned count=(size+2047)/2048,fresh[32],found=0;
    for (unsigned c=2;c<8167 && found<count;c++)
        if (!get16(fat+c*2)) fresh[found++]=c;
    if (found!=count) goto done; /* no writes on an out-of-space refusal */
    for (unsigned c=0;c<count;c++) {
        set16(fat+fresh[c]*2,c+1<count?fresh[c+1]:0xffff);
        for (unsigned s=0;s<4;s++) {
            unsigned offset=c*2048+s*512,bytes=offset<size?size-offset:0;
            if (bytes>512) bytes=512;
            kmemset(sector,0,512);
            if (bytes) kmemcpy(sector,text+offset,bytes);
            if (fs_image_sector(disk,98+(fresh[c]-2)*4+s,sector,1)) goto done;
        }
    }
    for (unsigned i=0;i<32;i++)
        if (fs_image_sector(disk,2+i,fat+i*512,1) ||
            fs_image_sector(disk,34+i,fat+i*512,1)) goto done;
    if (!exists) {kmemset(e,0,32);kmemcpy(e,"AUTOEXECBAT",11);}
    e[11]|=32;set16(e+26,fresh[0]);set32(e+28,size);
    if (fs_image_sector(disk,66+entry/16,root+(entry/16)*512,1)) goto done;
    /* Only reclaim the old chain after the directory points at the new one. */
    for (unsigned i=0;i<old_count;i++) set16(fat+old[i]*2,0);
    for (unsigned i=0;i<32;i++)
        if (fs_image_sector(disk,2+i,fat+i*512,1) ||
            fs_image_sector(disk,34+i,fat+i*512,1)) goto done;
    rc=0;
done:
    kfree(fat);kfree(root);kfree(text);
    return rc;
}
